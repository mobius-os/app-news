import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { createHash } from 'node:crypto'

const EXPECTED_WASM_SHA256 = '83a0cd64fe133a146714ae7a8dd369cb26b19e9a0b0b2732e963a024795b5a79'

const [modulePath, wasmPath] = process.argv.slice(2)
if (!modulePath || !wasmPath) {
  console.error('Usage: node scripts/embed-xn-runtime.mjs <ptts_wasm.js> <ptts_wasm_bg.wasm>')
  process.exit(1)
}

const [moduleSource, wasm] = await Promise.all([
  readFile(resolve(modulePath), 'utf8'),
  readFile(resolve(wasmPath)),
])
const sha256 = createHash('sha256').update(wasm).digest('hex')
if (sha256 !== EXPECTED_WASM_SHA256) {
  throw new Error(`Unexpected XN runtime SHA-256: ${sha256}`)
}
const encoded = wasm.toString('base64')
const splitAt = 750_000
const parts = [encoded.slice(0, splitAt), encoded.slice(splitAt)]
if (parts.some((part) => part.length >= 1_048_000 || part.length % 4 !== 0)) {
  throw new Error('The embedded Wasm chunks do not fit the app source contract.')
}
const moduleOutput = `// Generated by scripts/embed-xn-runtime.mjs from XN Pocket TTS.\n` +
  `// Wasm SHA-256: ${sha256}\n` +
  `export const XN_PTTS_MODULE_SOURCE = ${JSON.stringify(moduleSource)}\n` +
  `export const XN_PTTS_WASM_BYTES = ${wasm.byteLength}\n` +
  `export const XN_PTTS_WASM_SHA256 = ${JSON.stringify(sha256)}\n`

await Promise.all([
  writeFile(new URL('../browser-tts-xn-module.js', import.meta.url), moduleOutput),
  writeFile(
    new URL('../browser-tts-xn-wasm-1.js', import.meta.url),
    `// Generated by scripts/embed-xn-runtime.mjs.\nexport const XN_PTTS_WASM_BASE64_1 = ${JSON.stringify(parts[0])}\n`,
  ),
  writeFile(
    new URL('../browser-tts-xn-wasm-2.js', import.meta.url),
    `// Generated by scripts/embed-xn-runtime.mjs.\nexport const XN_PTTS_WASM_BASE64_2 = ${JSON.stringify(parts[1])}\n`,
  ),
])
