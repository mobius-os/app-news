import { build } from 'esbuild'
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outputPath = join(root, 'browser-tts-worker-source.js')
const result = await build({
  entryPoints: [join(root, 'browser-tts-worker-entry.js')],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['es2022'],
  minify: true,
  legalComments: 'none',
  write: false,
})
const source = result.outputFiles[0].text
const generated = `// Generated by scripts/build-tts-worker.mjs.\nexport const POCKET_TTS_WORKER_SOURCE = ${JSON.stringify(source)}\n`

if (process.argv.includes('--check')) {
  let current = ''
  try { current = await readFile(outputPath, 'utf8') } catch {}
  if (current !== generated) {
    console.error('browser-tts-worker-source.js is stale; run npm run build:tts-worker')
    process.exitCode = 1
  }
} else {
  await writeFile(outputPath, generated)
}
