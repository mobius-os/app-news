// Bundles the browser TTS worker into a single embeddable source string.
// Rolldown is the compiler Möbius uses, and it comes from the shell's frontend
// install rather than a dependency of this app.
import { createRequire } from 'node:module'
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outputPath = join(root, 'browser-tts-worker-source.js')

const frontend = process.env.MOBIUS_FRONTEND_NODE_MODULES
const { rolldown } = frontend
  ? await import(pathToFileURL(
      createRequire(join(frontend, 'package.json')).resolve('rolldown'),
    ).href)
  : await import('rolldown')

const bundle = await rolldown({
  input: join(root, 'browser-tts-worker-entry.js'),
  platform: 'browser',
  tsconfig: false,
  transform: { target: 'es2022' },
})
const { output } = await bundle.generate({
  format: 'iife',
  minify: true,
  comments: { legal: false },
  codeSplitting: false,
})
await bundle.close()
const source = output[0].code
const generated = `// Generated by scripts/build-tts-worker.mjs.\nexport const POCKET_TTS_WORKER_SOURCE = ${JSON.stringify(source)}\n`

if (process.argv.includes('--check')) {
  let current = ''
  try { current = await readFile(outputPath, 'utf8') } catch {}
  if (current !== generated) {
    console.error('browser-tts-worker-source.js is stale; run npm run build:tts-worker')
    process.exitCode = 1
  }
} else {
  await writeFile(outputPath, generated)
}
